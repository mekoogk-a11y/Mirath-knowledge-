export function queryWaqfAssistant(userQuery: string): {
  text: string;
  sources: string[];
  disclaimer: string;
} {
  const cleanQuery = userQuery.trim().toLowerCase();

  // Guardrail check: Is the question completely unrelated to waqf?
  const waqfRelatedWords = [
    'وقف',
    'واقف',
    'موقوف',
    'ناظر',
    'ريع',
    'غلة',
    'عين',
    'حبس',
    'تسبيل',
    'صدقة جارية',
    'استبدال',
    'مصرف',
    'مصارف',
    'خيبر',
    'صك',
    'وثيقة',
    'أهلي',
    'ذري',
    'مشترك',
  ];

  const hasWaqfKeywords = waqfRelatedWords.some((w) => cleanQuery.includes(w));

  // If user asks completely unrelated topics (like weather, general programming, sports, etc.)
  if (!hasWaqfKeywords && cleanQuery.length > 5) {
    // Check if it's general greeting
    if (['مرحبا', 'السلام عليكم', 'أهلا', 'صباح الخير', 'مساء الخير', 'من أنت'].some((g) => cleanQuery.includes(g))) {
      return {
        text: 'وعليكم السلام ورحمة الله وبركاته. أهلاً بك! أنا «مساعد الوقف الذكي»، مساعد متخصص في أحكام الوقف في الفقه الإسلامي، أركانه، شروطه، أنواعه، مصارفه، وقاموس مصطلحاته. كيف يمكنني خدمتك في مسائل الوقف اليوم؟',
        sources: ['قسم الوقف وأحكامه — منصة المواريث'],
        disclaimer: WAQF_DISCLAIMER,
      };
    }

    return {
      text: NON_WAQF_RESPONSE,
      sources: ['منصة المواريث والوقف'],
      disclaimer: WAQF_DISCLAIMER,
    };
  }

  // Check against our specific knowledge base entries
  for (const item of waqfKnowledgeBase) {
    if (item.keywords.some((kw) => cleanQuery.includes(kw.toLowerCase()))) {
      return {
        text: item.response,
        sources: item.sources,
        disclaimer: WAQF_DISCLAIMER,
      };
    }
  }

  // Dynamic fallback for queries that contain waqf keywords but didn't match a specific preset:
  return {
    text: `بخصوص سؤالك المتعلق بالوقف:
هذه مسألة تفصيلية من مسائل الوقف، والأصل فيها وجوب الرجوع إلى شروط الواقف المنصوص عليها في صك الوقفية عملاً بالقاعدة الفقهية الكبرى: «شرط الواقف كنص الشارع». 
في المسائل المعاصرة أو المنازعات، تجب مراجعة عالم مختص في الفقه الإسلامي أو الجهة الرسمية المختصة بالأوقاف أو المحكمة الشرعية، لأن الحكم قد يختلف بحسب التفاصيل الدقيقة للأصل وقانون الدولة المعمول به.`,
    sources: ['القواعد الفقهية الكبرى', 'نظام الأوقاف العام'],
    disclaimer: WAQF_DISCLAIMER,
  };
}
